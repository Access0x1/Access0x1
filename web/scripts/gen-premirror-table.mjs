#!/usr/bin/env node
/**
 * gen-premirror-table.mjs — regenerate the README's "Pre-mirror per-chain deploys" address
 * table straight from the committed broadcasts, so it can NEVER drift (law #3: no contract
 * address is claimed unless it is in a committed `broadcast/.../<chainId>/` record).
 *
 * WHY THIS EXISTS. Its sibling `sync-readme-status.mjs` generates only the ✅/⏳ mirror
 * matrix; the address table below it was hand-maintained and unchecked by CI. An audit found
 * exactly the failures that invites — twelve addresses attributed to Ethereum Sepolia that
 * appear in NO broadcast record on any chain, and twelve more labelled "Optimism Sepolia"
 * that are Base Sepolia's (with explorer links pointing at the wrong explorer). A table a
 * human retypes is a table that lies eventually; this one is derived.
 *
 * WHAT COUNTS AS A PRE-MIRROR SET. The mirror lands via CreateX (a `CALL` with
 * `additionalContracts`), so a chain's own pre-mirror deploy is the newest run under
 * `broadcast/DeployAll.s.sol/<id>/` that carries DIRECT `CREATE`s of our contracts. Newest
 * wins because a chain may have been redeployed before cutover (Arc and Base both were).
 *
 * WHICH ADDRESS IS LISTED. Every deploy since the proxy migration emits an implementation
 * `CREATE` immediately followed by its `ERC1967Proxy`. The integrator address is the PROXY,
 * so a paired run lists proxies; an older bare run lists the contracts themselves and is
 * marked as such. Pairing by adjacency is what the deploy script actually does — verified by
 * reproducing the Arc, 0G, Fuji and Robinhood blocks byte-for-byte against the previous
 * hand-written table.
 *
 * Runs from `make sync`. `--check` exits 1 if the README is stale (CI).
 *
 * Usage:
 *   node web/scripts/gen-premirror-table.mjs           # rewrite the table
 *   node web/scripts/gen-premirror-table.mjs --check   # exit 1 if stale
 */
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { chainMeta } from './gen-deployments.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = resolve(HERE, '..', '..')
const BROADCAST_DIR = join(REPO_ROOT, 'broadcast', 'DeployAll.s.sol')
const README = join(REPO_ROOT, 'README.md')

const START = '<!-- PREMIRROR-ADDRESSES:START (generated by `make sync` — do not edit by hand) -->'
const END = '<!-- PREMIRROR-ADDRESSES:END -->'

/** Local/sim chain ids are never a real deploy. */
const LOCAL_CHAIN_IDS = new Set([31337])

/**
 * Extract the ordered CREATE list from one broadcast file, but ONLY if its recorded `chain`
 * matches the directory it sits in. The directory is not proof — a run file can carry a
 * different `chain` field, and trusting the path is how a Base Sepolia set ends up published
 * under Optimism Sepolia's name and explorer.
 */
function createsIn(file, expectedChainId) {
  let data
  try {
    data = JSON.parse(readFileSync(file, 'utf8'))
  } catch {
    return []
  }
  if (Number(data.chain) !== Number(expectedChainId)) return []
  return (data.transactions ?? [])
    .filter((t) => typeof t.transactionType === 'string' && t.transactionType.startsWith('CREATE'))
    .filter((t) => t.contractName && t.contractAddress)
    .map((t) => ({ name: t.contractName, address: String(t.contractAddress).toLowerCase() }))
}

/**
 * The pre-mirror deploy set for one chain, or null when the chain has none.
 *
 * @returns `{ entries, proxied }` — `entries` is `[{ name, address }]` in deploy order;
 *   `proxied` is true when the listed addresses are ERC1967 proxies.
 */
export function premirrorSet(chainId) {
  const dir = join(BROADCAST_DIR, String(chainId))
  if (!existsSync(dir)) return null
  // Newest first: the filename timestamp is the deploy order the mirror cutover followed.
  const runs = readdirSync(dir)
    .filter((f) => /^run-\d+\.json$/.test(f))
    .sort((a, b) => Number(b.match(/\d+/)[0]) - Number(a.match(/\d+/)[0]))

  for (const run of runs) {
    const creates = createsIn(join(dir, run), chainId)
    if (creates.length === 0) continue

    // Paired shape: impl immediately followed by its ERC1967Proxy. List the proxies.
    const paired = []
    for (let i = 0; i < creates.length; i++) {
      if (creates[i].name !== 'ERC1967Proxy' && creates[i + 1]?.name === 'ERC1967Proxy') {
        paired.push({ name: creates[i].name, address: creates[i + 1].address })
      }
    }
    if (paired.length > 0) return { entries: paired, proxied: true }

    // Older bare deploy: no proxies were emitted, so the contracts ARE the addresses.
    const bare = creates.filter((c) => c.name !== 'ERC1967Proxy')
    if (bare.length > 0) return { entries: bare, proxied: false }
  }
  return null
}

/** Every chain id with a committed broadcast directory, ascending. */
function chainIds() {
  if (!existsSync(BROADCAST_DIR)) return []
  return readdirSync(BROADCAST_DIR, { withFileTypes: true })
    .filter((d) => d.isDirectory() && /^\d+$/.test(d.name))
    .map((d) => Number(d.name))
    .filter((id) => !LOCAL_CHAIN_IDS.has(id))
    .sort((a, b) => a - b)
}

/** Build the full markdown table. Exported so a test can exercise the real logic. */
export function buildAddressTable() {
  const rows = []
  let anyBare = false
  for (const id of chainIds()) {
    const set = premirrorSet(id)
    if (!set) continue
    if (!set.proxied) anyBare = true
    const { name, explorer } = chainMeta(id)
    const label = `${name} (${id})`
    for (const { name: contract, address } of set.entries) {
      const cell = explorer ? `[\`${address}\`](${explorer}/address/${address})` : `\`${address}\``
      rows.push(`| ${label} | \`${contract}\`${set.proxied ? '' : ' *'} | ${cell} |`)
    }
  }
  const table = ['| Chain | Contract | Address |', '| --- | --- | --- |', ...rows].join('\n')
  const footnote = anyBare
    ? '\n\n\\* Deployed before the proxy migration — this address is the contract itself, not an ERC1967 proxy.'
    : ''
  return `${table}${footnote}`
}

function main() {
  const check = process.argv.includes('--check')
  const readme = readFileSync(README, 'utf8')
  const s = readme.indexOf(START)
  const e = readme.indexOf(END)
  if (s < 0 || e < 0) {
    console.error(`gen-premirror-table: markers not found in README.md.\n  expected: ${START}`)
    process.exit(1)
  }
  const next = `${readme.slice(0, s + START.length)}\n\n${buildAddressTable()}\n\n${readme.slice(e)}`
  if (next === readme) {
    if (!check) console.log('gen-premirror-table: README already up to date.')
    return
  }
  if (check) {
    console.error(
      'gen-premirror-table: README address table is STALE.\n' +
        '  Every address there must come from a committed broadcast record (law #3).\n' +
        '  Run `node web/scripts/gen-premirror-table.mjs` and commit the result.',
    )
    process.exit(1)
  }
  writeFileSync(README, next)
  console.log('gen-premirror-table: README address table regenerated from broadcast records.')
}

if (import.meta.url === `file://${process.argv[1]}`) main()
